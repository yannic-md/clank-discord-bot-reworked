from sqlalchemy import BigInteger
from sqlalchemy import Enum as SQLEnum
from sqlalchemy.orm import Mapped, mapped_column

from core.db.base import Base
from core.enums.language import DEFAULT_LANGUAGE, SupportedLanguage


class UserLanguage(Base):
    """Per-user bot configuration.

    One row per Discord user, keyed by its snowflake ID. `user_id` is not
    auto-incrementing since it is always supplied explicitly (the Discord
    user ID itself), never generated by the database.
    """

    __tablename__ = "languages_user"

    user_id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=False)
    language: Mapped[SupportedLanguage] = mapped_column(
        SQLEnum(
            SupportedLanguage,
            native_enum=True,
            length=8,
            values_callable=lambda enum_cls: [member.value for member in enum_cls],
        ),
        default=DEFAULT_LANGUAGE,
        server_default=DEFAULT_LANGUAGE.value,
        nullable=False,
    )
